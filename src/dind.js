// The Docker daemon in a container: a pair's daemon (slots.js) and the template's loader daemon (seed.js).
// Both run without privileges from the image `DAEMON_IMAGE` (linux/dind/Dockerfile): as user RUNNER_USER, in their own
// namespaces (rootless), without `--privileged`. A job that breaks out of its container thus only lands in this
// container as an ordinary user, not in the Docker VM. The same image serves as a tool for volumes
// (`asRoot`). Both daemons need a moment after starting before they answer.

const path = require('node:path');
const { SECOND } = require('./units');
const { lastLine } = require('./run');
const { msg } = require('./messages');

const DAEMON_IMAGE = 'runclub-dind:latest';
const RUNNER_USER = 1001; // the user `runner` in the runner image; the daemon runs as the same one
// The daemon only listens on this socket, which the runner mounts at the same path (DOCKER_HOST in linux/Dockerfile).
const PAIR_SOCKET = 'unix:///sock/docker.sock';
const DATA_ROOT = '/home/rootless/.local/share/docker'; // where the unprivileged daemon keeps images and containers
// What the unprivileged daemons need (the build service too, see caches.js): their own namespaces and their own
// /proc, which Docker's defaults otherwise forbid (see "Rootless mode" in Docker's docs). Instead of running entirely
// without seccomp, they run with Docker's default profile plus only the calls they need for that (linux/seccomp.json,
// generated by scripts/seccomp.js). The Docker CLI reads the file itself and sends its content to Docker; falling back to
// `unconfined` is deliberately not provided for. AppArmor is not active in Docker Desktop's VM (the list of
// active security modules does not name it, as of 2026-10-16); `apparmor=unconfined` only takes effect where Docker
// runs on a kernel with AppArmor whose default profile would forbid the daemons from mounting.
const SECCOMP_PROFILE = path.join(__dirname, '..', 'linux', 'seccomp.json');
const SECURITY_FLAGS = ['--security-opt', `seccomp=${SECCOMP_PROFILE}`, '--security-opt', 'apparmor=unconfined', '--security-opt', 'systempaths=unconfined'];
// Plus a TUN device for the daemon's network.
const DAEMON_FLAGS = ['--device', '/dev/net/tun', ...SECURITY_FLAGS];
const DAEMON_COMMAND = ['dockerd', `--host=${PAIR_SOCKET}`];
// A tool for volumes (set permissions, copy, measure): an image with a script as root – root
// only in its own container. The script follows.
const asRoot = (image) => ['--user', '0', '--entrypoint', 'sh', image, '-c'];
const READY_TRIES = 40;
const DAEMON_POLL = SECOND; // interval between questions until a daemon answers
const PROBE_TIMEOUT = 20 * SECOND; // how long a question to a daemon may take (to Docker itself too, see dockerwatch.js)

// Asks the daemon in container `container` (through `host`, otherwise through its usual socket) until it answers:
// at most READY_TRIES times at an interval of DAEMON_POLL; `cancelled()` stops earlier. Returns whether it answers.
async function waitForDaemon({ docker, sleep, container, host = null, cancelled = () => false }) {
  for (let attempt = 0; attempt < READY_TRIES && !cancelled(); attempt += 1) {
    const probe = await docker(['exec', container, 'docker', ...(host ? ['-H', host] : []), 'info', '--format', 'ok'], { timeout: PROBE_TIMEOUT });
    if (probe.code === 0) return true;
    await sleep(DAEMON_POLL);
  }
  return false;
}

// Why a daemon did not become ready: the last error line from its log, otherwise its last line.
// If the seccomp profile forbids a call, it says "operation not permitted"; then the message adds that.
// Returns a message to append (` – reason`) or '' (see messages.js).
async function whyNotReady(docker, container) {
  const found = await docker(['logs', '--tail', '30', container]);
  const lines = `${found.stdout ?? ''}\n${found.stderr ?? ''}`.split('\n');
  const line = lastLine(lines.filter((entry) => /\b(error|fatal)\b|denied|not permitted/i.test(entry)).join('\n')) || lastLine(lines.join('\n'));
  if (!line) return '';
  return msg(/operation not permitted/i.test(line) ? 'm_whyNotReadySeccomp' : 'm_whyNotReady', line);
}

module.exports = { waitForDaemon, whyNotReady, SECCOMP_PROFILE, SECURITY_FLAGS, DAEMON_IMAGE, RUNNER_USER, PAIR_SOCKET, DATA_ROOT, DAEMON_FLAGS, DAEMON_COMMAND, asRoot, READY_TRIES, DAEMON_POLL, PROBE_TIMEOUT };
